    /**
     * 把文本里的微信表情代码替换成 emoji 字符（照 `replaceEmojiCodes`）。
     *
     * 不正则：所有代码都是 `[xxx]` 形式，直接扫括号查表即可，O(n) 且无回溯风险。
     */
    fun replaceCodes(text: String): String {
        if (text.isEmpty() || !text.contains('[')) return text
        val sb = StringBuilder(text.length)
        var i = 0
        while (i < text.length) {
            if (text[i] == '[') {
                val end = text.indexOf(']', i + 1)
                if (end > i) {
                    val emoji = DICT[text.substring(i, end + 1)]
                    if (emoji != null) {
                        sb.append(emoji)
                        i = end + 1
                        continue
                    }
                }
            }
            sb.append(text[i])
            i++
        }
        return sb.toString()
    }
